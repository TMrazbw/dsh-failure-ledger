/**
 * DFL — factual session handoff.
 *
 * This module never summarizes with an LLM. It writes only facts already
 * collected by the projection/store: goal, successful edit/verify calls,
 * unresolved failures, context/usage facts, and short ids.
 */

import { redact } from './redact.js';

export const HANDOFF_ROUTE = '/api/failure-ledger.handoff';

/**
 * Render a deterministic handoff document.
 *
 * @param {{sessionId?: string, view?: object|null, failures?: object[], now?: number}} input - facts.
 * @returns {string} Markdown.
 */
export function renderHandoff(input = {}) {
  const sessionId = input.sessionId == null ? 'session' : String(input.sessionId);
  const view = input.view && typeof input.view === 'object' ? input.view : {};
  const handoff = view.handoff && typeof view.handoff === 'object' ? view.handoff : {};
  const context = view.context && typeof view.context === 'object' ? view.context : {};
  const usage = view.usage && typeof view.usage === 'object' ? view.usage : {};
  const failures = Array.isArray(input.failures) ? input.failures : [];
  const groups = groupFailures(failures);
  const now = Number.isFinite(input.now) ? input.now : Date.now();
  const lines = [
    `# Session handoff — ${shortId(sessionId)}`,
    '',
    `Generated: ${new Date(now).toISOString()}`,
    '',
    '## Goal',
    '',
    handoff.goal ? redact(handoff.goal, { maxLength: 300 }) : '（未记录）',
    '',
    '## Done',
    '',
  ];
  const successes = Array.isArray(handoff.successes) ? handoff.successes : [];
  if (successes.length === 0) lines.push('- （无成功编辑/验证记录）');
  for (const entry of successes.slice(-5)) {
    const rawArgs = typeof entry.args === 'string' ? entry.args : JSON.stringify(entry.args ?? '');
    const args = redact(rawArgs, { maxLength: 180 });
    lines.push(`- ${formatTime(entry.at)} ${entry.tool}${args ? `: ${args}` : ''}`);
  }
  lines.push('', '## Next / Open failures', '');
  if (groups.length === 0) lines.push('- （无未解决失败）');
  for (const group of groups.slice(0, 10)) {
    lines.push(`- ${group.fingerprint} · ${group.tool}/${group.category} · ${group.count} 次`);
  }
  lines.push('', '## Open questions', '');
  const claim = view.claim && typeof view.claim === 'object' ? view.claim : {};
  if (claim.lastClaimText) lines.push(`- 未验证完成声明：${redact(claim.lastClaimText, { maxLength: 180 })}`);
  else lines.push('- （无）');
  lines.push('', '## Key facts', '');
  const window = numberOrZero(context.window);
  const lastInput = numberOrZero(context.lastInputTokens);
  const lastOutput = numberOrZero(context.lastOutputTokens);
  lines.push(`- 上下文：${lastInput + lastOutput}${window > 0 ? ` / ${window}` : '（窗口未知）'}`);
  lines.push(`- 本会话请求：${numberOrZero(usage.requests)} · 失败：${failures.length}`);
  if (view.savedTokens) lines.push(`- 已节省 tokens：${numberOrZero(view.savedTokens)}`);
  lines.push('', `_Generated by dsh-failure-ledger; facts only, no LLM summary._`);
  return `${lines.join('\n')}\n`;
}

/**
 * Create the authenticated handoff route.
 *
 * @param {{getHandoff: (sessionId: string) => Promise<object>}} options - callback.
 * @returns {object} ConnectionFetchRoute.
 */
export function createHandoffRoute(options = {}) {
  const getHandoff = typeof options.getHandoff === 'function' ? options.getHandoff : null;
  return {
    path: HANDOFF_ROUTE,
    methods: ['POST'],
    requestBody: 'buffered',
    async fetch(request) {
      if (request?.method !== 'POST') return jsonResponse({ ok: false, error: 'method_not_allowed' }, 405);
      let body = {};
      try {
        body = await request.json();
      } catch {
        body = {};
      }
      const sessionId = body?.sessionId == null ? '' : String(body.sessionId);
      if (!sessionId) return jsonResponse({ ok: false, error: 'session_required' }, 400);
      if (!getHandoff) return jsonResponse({ ok: false, error: 'handoff_unavailable' }, 503);
      try {
        const result = await getHandoff(sessionId);
        return jsonResponse(result, result?.ok === false ? 500 : 200);
      } catch (error) {
        return jsonResponse({ ok: false, error: error instanceof Error ? error.message : String(error) }, 500);
      }
    },
  };
}

function groupFailures(entries) {
  const groups = new Map();
  for (const entry of entries) {
    const fingerprint = entry?.fingerprint;
    if (typeof fingerprint !== 'string') continue;
    const group = groups.get(fingerprint) ?? {
      fingerprint,
      tool: entry.tool ?? 'tool',
      category: entry.category ?? 'unknown',
      count: 0,
    };
    group.count += 1;
    groups.set(fingerprint, group);
  }
  return [...groups.values()].sort((left, right) => right.count - left.count);
}

function shortId(value) {
  const text = String(value);
  return text.length > 12 ? `${text.slice(0, 6)}…${text.slice(-4)}` : text;
}

function formatTime(value) {
  const number = Number(value);
  if (!Number.isFinite(number)) return '—';
  return new Date(number).toISOString();
}

function numberOrZero(value) {
  const number = Number(value);
  return Number.isFinite(number) && number > 0 ? Math.floor(number) : 0;
}

function jsonResponse(value, status) {
  return new Response(JSON.stringify(value), {
    status,
    headers: { 'content-type': 'application/json; charset=utf-8', 'cache-control': 'no-store' },
  });
}
